/**
 * دالة حساب نتائج مقياس ATEC الإكلينيكية والسيكومترية المعتمدة
 * @param {Object} scores كائن يحتوي على إجابات البنود { [itemId]: score }
 */
export function calculateATECPsychometrics(scores = {}) {
  let answeredCount = 0;
  let totalScore = 0;

  const domainScores = ATEC_DOMAINS.map(domain => {
    let domainSum = 0;
    let domainAnswered = 0;
    const [start, end] = domain.itemRange;
    const items = ATEC_ITEMS.filter(it => it.id >= start && it.id <= end);

    items.forEach(it => {
      const val = scores[it.id] !== undefined ? Number(scores[it.id]) : null;
      if (val !== null && !isNaN(val)) {
        domainSum += val;
        domainAnswered++;
        answeredCount++;
        totalScore += val;
      }
    });

    const percentage = domain.maxScore > 0 ? Math.round((domainSum / domain.maxScore) * 100) : 0;
    
    // تقييم شدة المجال الفرعي
    let severityLevel = 'طبيعي / متقن';
    let severityColor = '#059669';
    if (percentage >= 70) {
      severityLevel = 'قصور حاد';
      severityColor = '#dc2626';
    } else if (percentage >= 45) {
      severityLevel = 'قصور متوسط';
      severityColor = '#d97706';
    } else if (percentage >= 25) {
      severityLevel = 'قصور بسيط';
      severityColor = '#2563eb';
    }

    return {
      ...domain,
      score: domainSum,
      answered: domainAnswered,
      totalItems: domain.itemsCount,
      percentage,
      severityLevel,
      severityColor,
    };
  });

  const totalItems = ATEC_ITEMS.length; // 77
  const isComplete = answeredCount === totalItems;
  const progressPercent = Math.round((answeredCount / totalItems) * 100);

  // التصنيف الإكلينيكي المعتمد لـ ATEC الصادر عن معهد أبحاث التوحد (ARI):
  // 0 - 31: تحسن ملحوظ جداً / حدود نمائية طبيعية أو طفيفة جداً (Minimal / Near Normal)
  // 32 - 50: أعراض طيف توحد بسيطة / مستوى دعم خفيف (Mild ASD Symptoms)
  // 51 - 103: أعراض طيف توحد متوسطة / مستوى دعم معتدل وجوهري (Moderate ASD Symptoms)
  // 104 - 180: أعراض طيف توحد شديدة / مستوى دعم مكثف وشامل (Severe ASD Symptoms)

  let severityKey = 'minimal';
  let severityLabel = 'حدود نمائية طبيعية / تحسن ملحوظ جداً (Minimal / Near Normal)';
  let severityBadgeClass = 'b-gr';
  let severityColor = '#059669';
  let percentileRange = 'أفضل من 90% من العينة الإكلينيكية';
  let clinicalImpression = '';
  let recommendations = '';

  if (totalScore <= 31) {
    severityKey = 'minimal';
    severityLabel = 'حدود طبيعية / أعراض طفيفة جداً (Minimal Impairment)';
    severityBadgeClass = 'b-gr';
    severityColor = '#059669';
    percentileRange = 'أفضل من 90% من المفحوصين (مؤشر استقلالية عالٍ)';
    clinicalImpression = `أحرز المفحوص درجة كلية منخفضة (${totalScore} من 180) على مقياس تقييم علاج التوحد (ATEC)، وهي تقع ضمن نطاق الحدود النمائية الطبيعية أو الأعراض البسيطة للغاية (0 - 31). يُظهر الطفل كفاءة وظيفية متقدمة في التواصل والاستجابة الاجتماعية، مع انحسار واضح للسلوكيات النمطية والاضطرابات الحسية. هذا المؤشر يعكس استجابة تأهيلية إيجابية ممتازة وقدرة عالية على الاستقلالية والتكيف البيئي والمدرسي.`;
    recommendations = `1. الاستمرار في برامج الدمج الصفي الشامل وتكثيف الأنشطة الاجتماعية والمجتمعية.\n2. تعزيز المهارات الأكاديمية ومهارات التفكير المجرد والمحادثة المتقدمة.\n3. تدريب الطفل على حل المشكلات وإدارة المواقف الاجتماعية المعقدة ومهارات القيادة الذاتية.\n4. إجراء تقييم متابعة دوري كل 6 أشهر لتوثيق استقرار وثبات المكاسب النمائية المكتسبة.`;
  } else if (totalScore >= 32 && totalScore <= 50) {
    severityKey = 'mild';
    severityLabel = 'أعراض طيف توحد بسيطة (Mild ASD Symptoms)';
    severityBadgeClass = 'b-bl';
    severityColor = '#2563eb';
    percentileRange = 'الدرجة تقع بين الرتبة المئينية 70% إلى 89%';
    clinicalImpression = `أحرز المفحوص درجة كلية (${totalScore} من 180) على مقياس ATEC، تقع في النطاق الخفيف / البسيط (32 - 50). يمتلك الطفل مهارات تواصلية واجتماعية أولية جيدة، إلا أنه يُظهر بعض الصعوبات في التفاعل التبادلي المستمر أو بعض الحساسيات الحسية والأنماط التكرارية الخفيفة. تعتبر هذه الدرجة مؤشراً إيجابياً يعكس استجابة جيدة لبرامج التأهيل مع قابلية ممتازة للدمج وتطوير السلوك التكيفي.`;
    recommendations = `1. التركيز على مهارات الحوار التبادلي (Pragmatics) وبدء واستمرار المحادثة مع الأقران.\n2. إدراج أهداف التفاعل الاجتماعي ضمن الخطة التربوية الفردية (IEP) وتبادل الأدوار في الألعاب.\n3. تطبيق برامج التدخل السلوكي لمعالجة أي سلوكيات روتينية أو نمطية قد تعيق التعلم الصفي.\n4. دعم وتدريب الأسرة على الاستراتيجيات المنزلية لتعزيز التواصل في المواقف الطبيعية.`;
  } else if (totalScore >= 51 && totalScore <= 103) {
    severityKey = 'moderate';
    severityLabel = 'أعراض طيف توحد متوسطة (Moderate ASD Symptoms)';
    severityBadgeClass = 'b-or';
    severityColor = '#d97706';
    percentileRange = 'الدرجة تقع بين الرتبة المئينية 30% إلى 69%';
    clinicalImpression = `أحرز المفحوص درجة كلية (${totalScore} من 180) على مقياس ATEC، وهي تقع ضمن نطاق الأعراض المتوسطة (51 - 103). يُظهر الطفل قصوراً ملحوظاً في مجالي التواصل اللفظي والتفاعل الاجتماعي، مصحوباً ببعض الاضطرابات الحسية والمعرفية والمشكلات السلوكية كفرط الحركة ونوبات الغضب أو مقاومة التغيير. يحتاج المفحوص إلى خطة علاجية تأهيلية متعددة التخصصات توفر دعماً منتظماً ومكثفاً.`;
    recommendations = `1. تصميم خطة تربوية فردية (IEP) شاملة تركز على مهارات التواصل الوظيفي ونظام التواصل المعزز والبديل (AAC) إذا لزم الأمر.\n2. جلسات علاج نطق وتخاطب مكثفة (2 إلى 3 جلسات أسبوعياً) لتعزيز اللغة الاستقبالية والتعبيرية.\n3. جلسات تكامل حسي وعلاج وظيفي لتنظيم المثيرات ومعالجة فرط أو ضعف الاستجابة الحسية.\n4. برنامج تحليل سلوك تطبيقي (ABA) لمعالجة نوبات الغضب والاندفاعية وبناء السلوكيات البديلة المتوافقة.`;
  } else {
    severityKey = 'severe';
    severityLabel = 'أعراض طيف توحد شديدة / مستوى دعم مكثف (Severe ASD Symptoms)';
    severityBadgeClass = 'b-rd';
    severityColor = '#dc2626';
    percentileRange = 'الدرجة تقع في الشريحة العليا (أعلى من الرتبة المئينية 70% في الشدة)';
    clinicalImpression = `أحرز المفحوص درجة كلية مرتفعة (${totalScore} من 180) على مقياس ATEC، تقع ضمن نطاق الأعراض الشديدة (104 - 180). يعاني المفحوص من قصور حاد وجوهري في كافة المجالات النمائية: انعدام أو محدودية بالغة في التواصل اللفظي وغير اللفظي، انعزال اجتماعي عميق، سلوكيات نمطية مفرطة، ومشكلات سلوكية وصحية تؤثر على استقراره اليومي. يتطلب الطفل برنامج تدخل علاجي وسلوكي شامل ومكثف جداً تحت إشراف فريق متخصص.`;
    recommendations = `1. برنامج تدخل سلوكي مكثف وفردي (Intensive ABA) بمعدل مرتفع لبناء المهارات الأساسية وتعديل السلوكيات المعيقة.\n2. إدخال وتدريب الطفل على التواصل البصري البديل (نظام بيكس PECS أو لوحات التواصل التفاعلية الإلكترونية).\n3. برنامج تكامل حسي وعلاج وظيفي يومي لتخفيف التحسسات اللمسية والسمعية وضبط التوتر الحركي.\n4. متابعة طبية وفحوصات للجهاز الهضمي وأنماط النوم بالتعاون مع أطباء الأطفال والمخ والأعصاب.\n5. تدريب الأسرة على أساليب إدارة السلوكيات الحادة وتأمين البيئة المنزلية لضمان سلامة الطفل.`;
  }

  return {
    isComplete,
    answeredCount,
    totalItems,
    progressPercent,
    rawScore: totalScore,
    maxScore: 180,
    minScore: 0,
    percentage: `${Math.round((totalScore / 180) * 100)}%`,
    severityKey,
    severityLabel,
    severityBadgeClass,
    severityColor,
    percentileRange,
    clinicalImpression,
    recommendations,
    domainScores,
  };
}

/**
 * دالة استدعاء متوافقة مع بنك المقاييس
 */
export function calculateATECScore(answers = {}) {
  return calculateATECPsychometrics(answers);
}
