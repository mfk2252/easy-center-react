/**
 * الحصول على التواريخ الميلادية لمناسبة معينة في سنة ميلادية محددة
 * يدعم المناسبات الهجرية الديناميكية التي قد تتكرر مرتين في سنة شمسية واحدة (مثل 2028)
 */
export function getInternationalDayDates(item, year) {
  const y = Number(year) || new Date().getFullYear();

  if (item.isHijri && item.hijriKey) {
    const tableEntry = ISLAMIC_HOLIDAYS_TABLE[item.hijriKey];
    if (tableEntry && tableEntry[y]) {
      const val = tableEntry[y];
      return Array.isArray(val) ? val : [val];
    }
    // حساب تقديري احتياطي إذا كانت السنة خارج جدول البيانات المباشر
    // الدورة الهجرية تتراجع قرابة 11 يوماً كل سنة ميلادية
    const baseYear = 2026;
    const baseDateStr = (tableEntry && tableEntry[baseYear]) || `${y}-03-15`;
    const singleBase = Array.isArray(baseDateStr) ? baseDateStr[0] : baseDateStr;
    const [by, bm, bd] = singleBase.split('-').map(Number);
    const diffYears = y - baseYear;
    const estimatedDate = new Date(y, bm - 1, bd - (diffYears * 11));
    const em = String(estimatedDate.getMonth() + 1).padStart(2, '0');
    const ed = String(estimatedDate.getDate()).padStart(2, '0');
    return [`${y}-${em}-${ed}`];
  }

  const m = String(item.month || 1).padStart(2, '0');
  const d = String(item.day || 1).padStart(2, '0');
  return [`${y}-${m}-${d}`];
}

/**
 * الحصول على تاريخ اليوم العالمي كقيمة واحدة افتراضية لسنة محددة (YYYY-MM-DD)
 */
export function getInternationalDayDate(item, year) {
  const dates = getInternationalDayDates(item, year);
  return dates[0];
}

/**
 * البحث عن المناسبات الموافقة لتاريخ معين (YYYY-MM-DD)
 */
export function getInternationalDaysForDate(dateStr) {
  if (!dateStr) return [];
  const parts = dateStr.split('-');
  if (parts.length < 3) return [];
  const year = parseInt(parts[0], 10);
  const m = parseInt(parts[1], 10);
  const d = parseInt(parts[2], 10);

  return INTERNATIONAL_DAYS.filter(item => {
    if (item.isHijri) {
      const dates = getInternationalDayDates(item, year);
      return dates.includes(dateStr);
    }
    return item.month === m && item.day === d;
  });
}

/**
 * جلب جميع الأيام والمناسبات منسقة مع تواريخ السنة المحددة
 */
export function getAllInternationalDaysForYear(year) {
  const targetYear = year || new Date().getFullYear();
  const list = [];

  INTERNATIONAL_DAYS.forEach(item => {
    const dates = getInternationalDayDates(item, targetYear);
    dates.forEach(dateVal => {
      const [, m, d] = dateVal.split('-').map(Number);
      list.push({
        ...item,
        formattedDate: dateVal,
        displayDate: `${d} ${getMonthNameAr(m)} (${targetYear})`,
        month: m,
        day: d,
      });
    });
  });

  return list.sort((a, b) => a.formattedDate.localeCompare(b.formattedDate));
}

export function getMonthNameAr(monthIndex1Based) {
  const months = [
    'يناير', 'فبراير', 'مارس', 'أبريل', 'مايو', 'يونيو',
    'يوليو', 'أغسطس', 'سبتمبر', 'أكتوبر', 'نوفمبر', 'ديسمبر'
  ];
  return months[monthIndex1Based - 1] || '';
}
