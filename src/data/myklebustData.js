/**
 * حساب المعاملات السيكومترية والتشخيصية لمقياس مايكل بيست (Myklebust PRS)
 */
export function calculateMyklebustPsychometrics(scores = {}) {
  let totalRawScore = 0;
  let verbalScore = 0;
  let nonVerbalScore = 0;
  let answeredCount = 0;

  const dimensionsResults = MYKLEBUST_DIMENSIONS.map(dim => {
    const dimItems = MYKLEBUST_ITEMS.filter(it => it.dimensionId === dim.id);
    let rawScore = 0;
    let dimAnswered = 0;

    dimItems.forEach(item => {
      const val = scores[item.id];
      if (val !== undefined && val !== null && val !== '') {
        const numVal = Number(val);
        rawScore += numVal;
        dimAnswered++;
      } else {
        // متوسط طبيعي افتراضي 3 إذا لم يُجب
        rawScore += 3;
      }
    });

    totalRawScore += rawScore;
    answeredCount += dimAnswered;

    if (dim.scaleGroup === 'verbal') {
      verbalScore += rawScore;
    } else {
      nonVerbalScore += rawScore;
    }

    const percentage = Math.round((rawScore / dim.maxScore) * 100);
    const isDeficit = rawScore <= dim.cutoffScore;

    let severity = 'أداء عادي / متوسط';
    let severityKey = 'normal';
    let severityColor = '#059669';

    if (rawScore <= Math.round(dim.maxScore * 0.45)) {
      severity = 'صعوبة شديدة دالة';
      severityKey = 'severe';
      severityColor = '#dc2626';
    } else if (isDeficit) {
      severity = 'صعوبة متوسطة (دون المتوسط)';
      severityKey = 'moderate';
      severityColor = '#ea580c';
    } else if (rawScore > Math.round(dim.maxScore * 0.8)) {
      severity = 'أداء متفوق / مرتفع';
      severityKey = 'superior';
      severityColor = '#16a34a';
    }

    return {
      ...dim,
      rawScore,
      score: rawScore,
      answeredCount: dimAnswered,
      totalItems: dimItems.length,
      percentage,
      severity,
      severityKey,
      severityColor,
      isDeficit,
      levelLabel: severity,
    };
  });

  const verbalPercentage = Math.round((verbalScore / 45) * 100);
  const nonVerbalPercentage = Math.round((nonVerbalScore / 75) * 100);
  const totalPercentage = Math.round((totalRawScore / 120) * 100);

  // تشخيص المجال اللفظي (الحد الفاصل 27 من 45)
  const isVerbalDeficit = verbalScore < 27;
  // تشخيص المجال غير اللفظي (الحد الفاصل 45 من 75)
  const isNonVerbalDeficit = nonVerbalScore < 45;

  // التصنيف والقرار التشخيصي العام لمقياس مايكل بيست:
  // الدرجة الكلية < 72 -> صعوبة تعلم مؤكدة
  // الدرجة الكلية 72 - 84 -> فئة حدية
  // الدرجة الكلية >= 85 -> عادي / لا توجد صعوبة
  let overallStatus = 'أداء عادي / لا توجد صعوبات تعلم';
  let overallKey = 'normal';
  let overallColor = '#059669';
  let diagnosisType = 'طبيعي (Normal)';
  let conclusionText = 'تقع درجات التلميذ في النطاق الطبيعي فوق محك القطع لمقياس مايكل بست (الدرجة الكلية أعلى من 72، والمجالين اللفظي وغير اللفظي طبيعيان).';

  if (totalRawScore < 72 || isVerbalDeficit || isNonVerbalDeficit) {
    overallStatus = 'صعوبة تعلم محتملة / مؤكدة إكلينيكياً';
    overallKey = 'severe';
    overallColor = '#dc2626';

    if (isVerbalDeficit && isNonVerbalDeficit) {
      diagnosisType = 'صعوبات تعلم شاملة (لفظية وغير لفظية)';
      conclusionText = `أظهر التلميذ انخفاضاً دالاً في المجالين اللفظي (${verbalScore}/45) وغير اللفظي (${nonVerbalScore}/75) بمجموع كلي (${totalRawScore}/120) دون محك القطع، مما يؤكد حاجته لبرنامج صعوبات التعلم وخطة فردية شاملة.`;
    } else if (isVerbalDeficit) {
      diagnosisType = 'صعوبات تعلم لفظية نمائية وأكاديمية (Verbal LD)';
      conclusionText = `يعاني التلميذ من قصور نوعي في المجال اللفظي (${verbalScore}/45 - أقل من المحك 27) خاصة في الاستيعاب واللغة المنطوقة، بينما المجال غير اللفظي طبيعي نسبياً (${nonVerbalScore}/75).`;
    } else if (isNonVerbalDeficit) {
      diagnosisType = 'صعوبات تعلم غير لفظية (Non-Verbal LD)';
      conclusionText = `يعاني التلميذ من قصور نوعي في المجال غير اللفظي (${nonVerbalScore}/75 - أقل من المحك 45) في التوجه المكاني أو التناسق الحركي أو السلوك الاجتماعي، بينما المجال اللفظي طبيعي (${verbalScore}/45).`;
    } else {
      diagnosisType = 'صعوبة تعلم محتملة وفق الدرجة الكلية';
      conclusionText = `حصل التلميذ على مجموع كلي (${totalRawScore}/120) دون محك القطع الكلي (72)، مما يشير إلى وجود صعوبات تعلم تتطلب تدخلاً علاجياً في غرفة المصادر.`;
    }
  } else if (totalRawScore <= 84) {
    overallStatus = 'فئة حدية (معرض لخطر صعوبات التعلم)';
    overallKey = 'borderline';
    overallColor = '#d97706';
    diagnosisType = 'فئة حدية (Borderline / At-Risk)';
    conclusionText = `تقع درجات التلميذ في النطاق الحدي القريب من محك الصعوبة (${totalRawScore}/120). يوصى بالملاحظة والتدخل المبكر داخل الفصل العادي.`;
  }

  const deficitDimensions = dimensionsResults.filter(d => d.isDeficit);
  const criticalItems = MYKLEBUST_ITEMS.filter(it => (scores[it.id] || 3) <= 2);

  return {
    totalRawScore,
    maxRawScore: 120,
    totalPercentage,
    overallPercentage: totalPercentage,
    verbalScore,
    verbalMaxScore: 45,
    verbalPercentage,
    isVerbalDeficit,
    nonVerbalScore,
    nonVerbalMaxScore: 75,
    nonVerbalPercentage,
    isNonVerbalDeficit,
    answeredCount,
    totalAnswered: answeredCount,
    totalItems: 24,
    dimensionsResults,
    dimensionScores: dimensionsResults,
    deficitDimensions,
    criticalItems,
    overallStatus,
    overallKey,
    overallColor,
    diagnosisType,
    conclusionText,
    diagnosisDescription: conclusionText,
    recommendationSummary: conclusionText,
  };
}
