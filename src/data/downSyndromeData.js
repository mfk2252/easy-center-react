/**
 * دالة مساعدة لحساب نتيجة وتصنيف مقاييس متلازمة داون
 */
export function calculateDownSyndromeScore(scaleId, responses = {}) {
  const scale = DOWN_SYNDROME_SCALES.find(s => s.id === scaleId);
  if (!scale) return { score: 0, maxScore: 20, percentage: 0, level: 'غير محدد' };

  let totalScore = 0;
  const items = scale.items || [];
  const maxScore = items.length;

  items.forEach(item => {
    const val = responses[item.id];
    if (val !== undefined && val !== null && !isNaN(val)) {
      totalScore += Number(val);
    }
  });

  const percentage = maxScore > 0 ? Math.round((totalScore / maxScore) * 100) : 0;

  let level = 'مستوى متقدم (كفاءة نمائية عالية)';
  let severityColor = '#059669';

  if (percentage < 45) {
    level = 'بحاجة لتدخل وتأهيل مكثف';
    severityColor = '#dc2626';
  } else if (percentage < 75) {
    level = 'مستوى متوسط (في طور الاكتساب والنمو)';
    severityColor = '#d97706';
  }

  return {
    score: totalScore,
    maxScore,
    percentage,
    level,
    severityColor,
  };
}
