/**
 * Calculates complete psychometrics for CARS-2
 * @param {Object} scores - Key-value map of { item_id: score_value }
 */
export function calculateCARS2Psychometrics(scores = {}) {
  const answeredCount = Object.keys(scores).filter(k => scores[k] !== undefined && scores[k] !== null && scores[k] !== '').length;
  const isComplete = answeredCount === 15;

  let totalRawScore = 0;
  Object.values(scores).forEach(val => {
    const num = Number(val);
    if (!isNaN(num) && num >= 1) totalRawScore += num;
  });

  // Round to nearest 0.5
  totalRawScore = Math.round(totalRawScore * 2) / 2;

  // Approximate T-score and Percentile if incomplete
  let lookup = CARS2_NORM_TABLE.find(entry => Math.abs(entry.raw - totalRawScore) < 0.3);
  if (!lookup) {
    if (totalRawScore <= 15) lookup = CARS2_NORM_TABLE[0];
    else lookup = CARS2_NORM_TABLE[CARS2_NORM_TABLE.length - 1];
  }

  // Diagnostic Severity Classification
  let severityKey = 'none';
  let severityLabel = 'ضمن الحدود الطبيعية (لا تقع ضمن طيف التوحد)';
  let severityBadgeClass = 'b-gr';
  let severityColor = 'var(--ok, #059669)';
  let clinicalImpression = '';

  if (totalRawScore < 30) {
    severityKey = 'none';
    severityLabel = 'ضمن الحدود الطبيعية (لا توجد مؤشرات لطيف التوحد)';
    severityBadgeClass = 'b-gr';
    severityColor = 'var(--ok, #059669)';
    clinicalImpression = 'الدرجة الكلية المحققة تقع دون نقطة القطع التشخيصية (Cutoff < 30). لا توجد أدلة إكلينيكية كافية تدعم وجود اضطراب طيف التوحد. يوصى بمتابعة النمو النمائي العام والمهارات الأكاديمية.';
  } else if (totalRawScore >= 30 && totalRawScore <= 36.5) {
    severityKey = 'mild_moderate';
    severityLabel = 'أعراض طيف توحد بسيطة إلى متوسطة (Mild-to-Moderate Autism)';
    severityBadgeClass = 'b-or';
    severityColor = 'var(--warn, #d97706)';
    clinicalImpression = 'الدرجة الكلية تقع في النطاق التشخيصي للأعراض البسيطة إلى المتوسطة (30.0 - 36.5). يُظهر الطفل سمات صريحة لطيف التوحد في التواصل والتفاعل الاجتماعي والمرونة السلوكية تستدعي إعداد خطة تربوية فردية (IEP) وتدخلات علاجية وتأهيلية مركزة.';
  } else {
    severityKey = 'severe';
    severityLabel = 'أعراض طيف توحد شديدة / حادة (Severe Autism)';
    severityBadgeClass = 'b-re';
    severityColor = 'var(--err, #dc2626)';
    clinicalImpression = 'الدرجة الكلية تقع في النطاق الشديد / الحاد (37.0 - 60.0). يُظهر الطفل أعراضاً مكثفة وعميقة لطيف التوحد تعيق التكيف والتواصل بشكل جوهري. يوصى ببرنامج تدخل سلوكي شامل ومكثف (ABA)، وتأهيل تخاطبي ووظيفي، وجلسات تكامل حسي.';
  }

  // Domain-specific breakdown
  const domainScores = CARS2_DOMAINS.map(d => {
    let sum = 0;
    let max = d.items.length * 4;
    let count = 0;
    d.items.forEach(itemId => {
      const val = Number(scores[itemId] || scores[`c${itemId}`] || scores[`item_${itemId}`] || 0);
      if (val > 0) {
        sum += val;
        count++;
      }
    });
    const avg = count > 0 ? (sum / count).toFixed(1) : '0';
    const pct = max > 0 ? Math.round((sum / max) * 100) : 0;
    return {
      ...d,
      score: sum,
      maxScore: max,
      avg: Number(avg),
      percentage: pct,
      answered: count,
      totalItems: d.items.length,
    };
  });

  return {
    isComplete,
    answeredCount,
    totalItems: 15,
    rawScore: totalRawScore,
    maxScore: 60,
    minScore: 15,
    percentage: `${Math.round((totalRawScore / 60) * 100)}%`,
    tScore: lookup.tScore,
    percentile: lookup.percentile,
    severityKey,
    severityLabel,
    severityBadgeClass,
    severityColor,
    clinicalImpression,
    domainScores,
  };
}
