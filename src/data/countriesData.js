/**
 * خريطة سريعة بالرمز للوصول المباشر O(1)
 */
export const COUNTRIES_BY_CODE = Object.fromEntries(
  COUNTRIES.map(c => [c.code.toUpperCase(), c])
);

/**
 * قائمة العملات المستخرجة من الدول لدعم الاختيار المخصص
 */
export const GLOBAL_CURRENCIES = Array.from(
  new Map(
    COUNTRIES.map(c => [
      c.currency,
      {
        code: c.currency,
        name: c.currencyNameAr,
        nameEn: c.currencyNameEn,
        country: c.nameAr,
        flag: c.flag,
        symbol: c.currencySymbol,
        label: `${c.flag} ${c.currencyNameAr} — ${c.nameAr} (${c.currency})`,
      }
    ])
  ).values()
);

/**
 * البحث عن دولة بواسطة الرمز أو الاسم العربي أو الإنجليزي أو كود الهاتف
 */
export function getCountryByCode(code) {
  if (!code) return COUNTRIES_BY_CODE['SA'] || COUNTRIES[0];
  const upper = String(code).trim().toUpperCase();
  if (COUNTRIES_BY_CODE[upper]) return COUNTRIES_BY_CODE[upper];

  // محاولة المطابقة مع العملة أو كود الهاتف
  const byPhone = COUNTRIES.find(c => c.phoneCode === code || c.phoneCode.replace('+', '') === code);
  if (byPhone) return byPhone;

  const byName = COUNTRIES.find(c => 
    c.nameAr.includes(code) || 
    c.nameEn.toLowerCase().includes(String(code).toLowerCase())
  );
  return byName || COUNTRIES_BY_CODE['SA'] || COUNTRIES[0];
}

/**
 * اقتراح إعدادات الدولة التلقائية
 */
export function getCountryPresets(countryCode) {
  const country = getCountryByCode(countryCode);
  return {
    countryCode: country.code,
    countryNameAr: country.nameAr,
    countryNameEn: country.nameEn,
    flag: country.flag,
    phoneCode: country.phoneCode,
    currency: country.currency,
    currencySymbol: country.currencySymbol,
    currencyNameAr: country.currencyNameAr,
    defaultCity: country.defaultCity,
    suggestedAddress: `${country.nameAr} - ${country.defaultCity}`,
  };
}

/**
 * جلب رمز العملة لأي كود
 */
export function resolveCurrencySymbol(currencyCode) {
  if (!currencyCode) return 'SAR';
  const found = COUNTRIES.find(c => c.currency === currencyCode);
  return found ? (found.currencySymbol || found.currency) : currencyCode;
}
